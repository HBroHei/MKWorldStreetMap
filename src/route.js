document.getElementById("btn-find-route").addEventListener('click', () => {
    if(startCoord && endCoord){
        // Define GeoJSON point formats for the finder
        const startPoint = {
            type: 'Feature',
            geometry: {
                type: 'Point',
                coordinates: startCoord
            }
        };
        const endPoint = {
            type: 'Feature',
            geometry: {
                type: 'Point',
                coordinates: endCoord
            }
        };

        // 4. Calculate the path
        const result = pathFinder.findPath(startPoint, endPoint);

        if (result && result.path) {
            console.log("Success");
            // Convert the result array of coordinates back to a format OpenLayers understands
            // geojson-path-finder exports coordinates as [lng, lat]
            const olCoordinates = result.path.map(coord => fromLonLat(coord));

            if (olCoordinates.length > 1) {
                olCoordinates.unshift(startCoordOL);
                olCoordinates.push(endCoordOL);
            }

            // 4. Render the trimmed line onto your OpenLayers map
            if(routeFeature) routeSource.removeFeature(routeFeature);
            routeFeature = new Feature({
                geometry: new LineString(olCoordinates)
            });

            routeSource.addFeature(routeFeature);

            map.getView().fit(routeFeature.getGeometry());
        } else {
            alert("Could not find a valid route between these two points. Check your topology!");
        }

        // Reset for the next routing attempt
        startCoord = null;
    }
    else{
        alert("Please set the start and / or the end point.");
    }
})